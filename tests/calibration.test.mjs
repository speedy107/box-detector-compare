import assert from 'node:assert/strict';
import {cameraProfile,sameCamera,referenceSample,createCalibration,restoreCalibration,calibratedDistance} from '../calibration.js';

const profile=cameraProfile({deviceId:'back-camera',facingMode:'environment',zoom:1},1000,1000);
const box={x1:400,y1:400,x2:600,y2:600,score:.95,classId:0};
const sample=referenceSample(box,1000,1000);
const calibration=createCalibration(Array(5).fill(sample),3,profile);
const estimate=(b,p=profile,others=[])=>calibratedDistance(b,1000,1000,calibration,p,others);
assert.equal(estimate(box).metres,3);
assert.equal(estimate({...box,x1:450,y1:450,x2:550,y2:550}).metres,6,'Half apparent size doubles depth');
assert.equal(estimate({...box,x1:300,y1:300,x2:700,y2:700}).metres,1.5,'Double apparent size halves depth');
assert.equal(estimate({...box,classId:1}).metres,3,'Equal-size blue and red blocks share the reference');
assert.equal(calibratedDistance({...box,x1:200,y1:200,x2:300,y2:300},500,500,calibration,profile).metres,3,'Downsampling the same frame preserves normalized geometry');
assert.equal(estimate({...box,x1:0}).metres,null,'Clipped outlines do not yield distances');
assert.equal(estimate({...box,score:.4}).metres,null,'Low-confidence outlines do not yield distances');
assert.equal(estimate({...box,x1:480,x2:520,y1:480,y2:520}).metres,null,'Very small outlines are rejected');
assert.equal(estimate({...box,x2:700}).metres,null,'Changed outline aspect requires matching the reference angle');
assert.equal(estimate(box,{...profile,zoom:2}).reason,'Recalibrate camera');
assert.equal(estimate(box,{...profile,deviceId:'other'}).metres,null);
assert.equal(estimate(box,{...profile,width:500}).metres,null);
assert.equal(estimate(box,null).metres,null,'Photo frames cannot reuse a camera reference');
assert.equal(calibratedDistance(box,1000,1000,null,profile).reason,'Calibrate first');
assert.equal(estimate(box,profile,[box,{...box}]).metres,null,'Overlapping detections cannot be trusted as whole blocks');
assert.throws(()=>createCalibration([sample],3,profile),/five/);
assert.throws(()=>createCalibration(Array(5).fill(sample),0,profile),/measured distance/);
assert.throws(()=>createCalibration(Array(5).fill(sample),3,{...profile,deviceId:''}),/identity/);
assert.throws(()=>createCalibration([...Array(4).fill(sample),{...sample,width:.25}],3,profile),/moved too much/);
assert.deepEqual(restoreCalibration(JSON.parse(JSON.stringify(calibration))),calibration);
assert.equal(restoreCalibration({...calibration,width:Infinity}),null);
assert.equal(restoreCalibration({...calibration,version:0}),null);
assert.equal(sameCamera(profile,{...profile,zoom:1.1}),false);
console.log('PASS: reference geometry, equal-size classes, image scaling, clipping, confidence, small/overlapping outlines, angle changes, camera/zoom changes, stable references and persistence validation.');
